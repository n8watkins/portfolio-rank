#!/usr/bin/env node
// GRADING_CRITERIA.md's rubric table is generated from pipeline/rubric.mjs,
// so the docs can never drift from what the grader sends.
//
//   node scripts/rubric-docs.mjs          rewrite the block between the markers
//   node scripts/rubric-docs.mjs --check  exit 1 when the block is out of date
//                                         (tests/rubric.test.mjs runs this check)
import fs from "fs";
import path from "path";
import { criteriaMarkdown } from "../pipeline/rubric.mjs";

export const DOC = path.join(import.meta.dirname, "..", "GRADING_CRITERIA.md");
export const START = "<!-- rubric:start (generated by scripts/rubric-docs.mjs from pipeline/rubric.mjs; do not edit by hand) -->";
export const END = "<!-- rubric:end -->";

/** The document with the generated block replaced; throws without markers. */
export function renderDoc(doc) {
  const a = doc.indexOf(START);
  const b = doc.indexOf(END);
  if (a < 0 || b < a) throw new Error(`GRADING_CRITERIA.md needs the markers ${START} and ${END}`);
  return `${doc.slice(0, a + START.length)}\n${criteriaMarkdown()}\n${doc.slice(b)}`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const doc = fs.readFileSync(DOC, "utf8");
  const next = renderDoc(doc);
  if (process.argv.includes("--check")) {
    if (next !== doc) {
      console.error("GRADING_CRITERIA.md is out of date with pipeline/rubric.mjs: run npm run docs:rubric");
      process.exit(1);
    }
    console.log("GRADING_CRITERIA.md matches pipeline/rubric.mjs");
  } else if (next !== doc) {
    fs.writeFileSync(DOC, next);
    console.log("GRADING_CRITERIA.md updated");
  } else {
    console.log("GRADING_CRITERIA.md already up to date");
  }
}
