function analyticsCheck(st, rd, requests, base) {
  const abs = (u) => {
    try {
      return new URL(u, base).href;
    } catch {
      return u;
    }
  };
  const srcs = [...(st?.scripts ?? []), ...(rd?.scripts ?? [])].map(abs);
  const inline = [...(st?.inline ?? []), ...(rd?.inline ?? [])];
  const found = {};
  for (const [name, p] of Object.entries(TOOLS)) {
    const how = [];
    if (srcs.some((u) => p.src.test(u))) how.push("script");
    if (inline.some((t) => p.inline.test(t))) how.push("inline");
    if ((requests ?? []).some((u) => p.src.test(u))) how.push("request");
    if (how.length) found[name] = how;
  }
  return { tools: Object.keys(found), how: found, any: Object.keys(found).some((t) => ASKED.includes(t)) };
}

// ---------- (7) basics ----------
function basicsCheck(st, rd, x, url, finalUrl, render) {
  if (!st || st.error) return null;
  const lang = (st.lang ?? rd?.lang ?? "").trim();
  const vp = st.viewport ?? rd?.viewport ?? "";
  const iconLink = (st.icons?.length ?? 0) + (rd?.icons?.length ?? 0) > 0;
  const https = /^https:/i.test(finalUrl ?? "");
  // The first hop of an http:// listed address (before its redirect to https) is not mixed content.
  const listedOrigin = /^http:/i.test(url) ? new URL(url).origin.toLowerCase() : null;
  const pageHttp = (render?.httpRequests ?? []).filter((u) => !/^http:\/\/(localhost|127\.)/.test(u) && !(listedOrigin && new URL(u).origin.toLowerCase() === listedOrigin));
  const mixed = https && ((st.insecure?.length ?? 0) + (rd?.insecure?.length ?? 0) + pageHttp.length + (render?.mixedConsole?.length ?? 0) > 0);
  return {
    favicon: iconLink || !!x?.faviconIco?.loads,
    faviconLink: iconLink,
    lang: lang || null,
    langOk: /^[a-z]{2,3}(-[a-z0-9]{2,8})*$/i.test(lang),
    viewport: vp || null,
    viewportOk: /width\s*=\s*device-width/i.test(vp),
    https,
    httpRedirectsToHttps: /^http:/i.test(url) ? https : null,
    mixedContent: mixed,
    mixedSamples: [...(st.insecure ?? []), ...(rd?.insecure ?? []), ...pageHttp].slice(0, 3),
  };
}

// ---------- run ----------
const sites = [];
for (const s of sample) {
  const f = fetched[s.url] ?? {};
  const r = rendered[s.url] ?? {};
  const base = f.finalUrl ?? r.finalUrl ?? s.url;
  // The listed address and wherever it redirects both count as the site.
  const siteHost = new Set([host(s.url), host(base), host(r.finalUrl ?? base)].filter(Boolean));
  sites.push({
    url: s.url,
    name: s.name,
    fetchStatus: f.status ?? f.error ?? null,
    renderError: r.renderError ?? null,
    meta: { static: metaCheck(r.static, siteHost, f, base), rendered: metaCheck(r.rendered, siteHost, f, r.finalUrl ?? base) },
    schema: { static: schemaCheck(r.static, siteHost, s.name, base), rendered: schemaCheck(r.rendered, siteHost, s.name, r.finalUrl ?? base) },
    fonts: fontCheck(r.fonts),
    crawl: crawlCheck(extra[s.url]),
    analytics: r.static || r.rendered ? analyticsCheck(r.static, r.rendered, r.requests, base) : null,
    basics: basicsCheck(r.static, r.rendered, extra[s.url], s.url, f.finalUrl ?? r.finalUrl, r),
  });
}

