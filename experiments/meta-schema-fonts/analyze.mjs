function walk(node, visit, depth = 0) {
  if (depth > 12 || !node || typeof node !== "object") return;
  if (Array.isArray(node)) return node.forEach((n) => walk(n, visit, depth + 1));
  visit(node, depth);
  for (const [k, v] of Object.entries(node)) if (k !== "@context") walk(v, visit, depth + 1);
}
const typesOf = (n) => [].concat(n["@type"] ?? []).map(String);

function schemaCheck(head, siteHost, ownerName, base) {
  if (!head || head.error) return null;
  const blocks = head.jsonld ?? [];
  const parsed = [];
  const errors = [];
  for (const b of blocks) {
    try {
      parsed.push(JSON.parse(b));
    } catch (e) {
      errors.push(String(e.message).slice(0, 80));
    }
  }
  const nodes = [];
  for (const p of parsed) walk(p, (n) => typesOf(n).length && nodes.push(n));
  for (const m of head.microdata ?? []) {
    if (!m.type) continue;
    nodes.push({ "@type": m.type.split(/\s+/).map((t) => t.replace(/^https?:\/\/schema\.org\//i, "")), ...m.props, _microdata: true });
  }
  const types = [...new Set(nodes.flatMap(typesOf))];
  const persons = nodes.filter((n) => typesOf(n).includes("Person"));
  const owner = new Set([...tokens(ownerName), ...tokens(head.title), ...(head.h1 ?? []).flatMap(tokens), ...[...siteHost].flatMap((h) => tokens(h.split(".")[0]))]);
  const ownerStrict = new Set(tokens(ownerName));
  const issues = [];
  const personNames = persons.map((p) => (typeof p.name === "string" ? p.name.trim() : null)).filter(Boolean);
  let personMatch = null;
  if (personNames.length) {
    const near = (t, set) => set.has(t) || [...set].some((o) => o.length >= 4 && t.length >= 4 && (o.startsWith(t) || t.startsWith(o)));
    personMatch = personNames.some((n) => tokens(n).some((t) => near(t, owner)));
    if (!personMatch) issues.push(`person-name-mismatch: ${personNames.join(", ").slice(0, 60)}`);
    if (!personNames.some((n) => tokens(n).some((t) => ownerStrict.has(t))) && personMatch) issues.push("person-matches-page-but-not-listed-name");
  }
  for (const n of personNames) if (PLACEHOLDER_NAME.test(n)) issues.push(`placeholder-name: ${n}`);
  // Addresses that should point at this site.
  for (const n of nodes) {
    for (const k of ["url", "@id"]) {
      const v = n[k];
      if (typeof v !== "string" || /^#/.test(v) || /^_:/.test(v)) continue;
      const h = host(v, base);
      if (!h) continue;
      if (PLACEHOLDER_HOST.test(h)) issues.push(`placeholder-url: ${h}`);
      else if (!siteHost.has(h) && !SOCIAL.test(h) && !LOGO_HOST.test(h) && typesOf(n).some((t) => /^(Person|WebSite|ProfilePage|WebPage)$/.test(t)) && !(typesOf(n).includes("Person") && !tokens(n.name).some((t) => owner.has(t))))
        issues.push(`other-host: ${h}`);
    }
  }
  const text = blocks.join(" ");
  if (/\{\{\s*[\w.]+\s*\}\}|lorem ipsum|\byour[ -]?name\b|yourwebsite|your-?domain/i.test(text)) issues.push("template-text");
  const uniq = [...new Set(issues)];
  let verdict;
  if (!blocks.length && !(head.microdata ?? []).length) verdict = "none";
  else if (!types.length && errors.length) verdict = "broken";
  else if (!types.length) verdict = "no-types";
  else if (uniq.some((i) => /^(placeholder|template|person-name-mismatch)/.test(i))) verdict = "junk";
  else if (uniq.some((i) => /^other-host/.test(i))) verdict = "suspect";
  else verdict = "plausible";
  return {
    jsonldBlocks: blocks.length,
    microdataItems: (head.microdata ?? []).length,
    rdfa: (head.rdfa ?? []).length,
    parseErrors: errors,
    types,
    personNames,
    personMatch,
    issues: uniq,
    verdict,
  };
}

