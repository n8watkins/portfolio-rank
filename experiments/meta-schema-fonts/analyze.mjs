/** next/font hashed names, "Inter Variable", quotes. */
function normFamily(f) {
  let s = f.trim().replace(/^["']|["']$/g, "").trim();
  const nx = s.match(/^__(.+?)(?:_Fallback)?_[0-9a-f]{5,8}$/i);
  if (nx) s = nx[1].replace(/_/g, " ");
  s = s.replace(/\s+(Fallback|Variable|VF)$/i, "").trim();
  // "Lato-Bold", "Inter SemiBold": one family declared per weight is still one family.
  s = s.replace(/[- ](Thin|Hairline|ExtraLight|UltraLight|Light|Regular|Book|Normal|Medium|SemiBold|DemiBold|Bold|ExtraBold|UltraBold|Black|Heavy|Italic)$/i, "").trim();
  return s;
}
function stackOf(css) {
  return css.split(",").map((f) => f.trim().replace(/^["']|["']$/g, "")).filter(Boolean);
}

function effectiveFamily(group, loaded) {
  const stack = stackOf(group.stack);
  const platform = Object.keys(group.platform ?? {}).map(fold);
  const generic = stack.map((f) => f.toLowerCase()).filter((f) => GENERIC.has(f)).pop() ?? "sans-serif";
  const kind = /mono/.test(generic) ? "mono" : /serif$/.test(generic) && generic !== "sans-serif" && generic !== "ui-sans-serif" ? "serif" : generic === "cursive" ? "cursive" : generic === "fantasy" ? "fantasy" : "sans";
  for (const raw of stack) {
    const f = normFamily(raw);
    const lf = f.toLowerCase();
    if (GENERIC.has(lf)) return { family: `system ${kind}`, kind, system: true, generic };
    if (loaded.has(fold(raw)) || loaded.has(fold(f))) return { family: f, kind, system: false, generic };
    if (SYSTEM_UI.test(lf)) return { family: "system sans", kind: "sans", system: true, generic };
    if (SYSTEM_UI_SERIF.test(lf)) return { family: "system serif", kind: "serif", system: true, generic };
    if (SYSTEM_UI_MONO.test(lf)) return { family: "system mono", kind: "mono", system: true, generic };
    if (WEB_SAFE.has(lf)) return { family: WEB_SAFE.get(lf), kind, system: true, generic };
    // Installed locally on the measuring machine (Chromium drew it).
    if (platform.some((p) => p.startsWith(fold(f)))) return { family: f, kind, system: false, generic };
  }
  return { family: `system ${kind}`, kind, system: true, generic };
}

function fontCheck(fonts) {
  if (!fonts) return null;
  const loaded = new Set(fonts.webfonts.filter((w) => w.status === "loaded").map((w) => fold(w.family)));
  const fam = new Map();
  let total = 0,
    totalBody = 0;
  for (const g of fonts.groups) {
    const stackFirst = normFamily(stackOf(g.stack)[0] ?? "");
    const icon = ICON.test(stackFirst) || g.pua > g.chars * 0.5;
    if (icon) continue;
    const e = effectiveFamily(g, loaded);
    const key = e.family;
    const f = fam.get(key) ?? { family: key, kind: e.kind, system: e.system, chars: 0, bodyChars: 0, decorative: false };
    f.chars += g.chars;
    f.bodyChars += g.bodyChars;
    f.decorative ||= DECORATIVE.test(key) || e.generic === "cursive" || e.generic === "fantasy";
    fam.set(key, f);
    total += g.chars;
    totalBody += g.bodyChars;
  }
  const list = [...fam.values()].sort((a, b) => b.chars - a.chars);
  for (const f of list) {
    f.share = total ? +(f.chars / total).toFixed(3) : 0;
    f.bodyShare = totalBody ? +(f.bodyChars / totalBody).toFixed(3) : 0;
  }
  const meaningful = list.filter((f) => f.share >= 0.02);
  const bodyFamilies = list.filter((f) => f.bodyShare >= 0.05);
  const decorativeBody = list.filter((f) => f.decorative && f.bodyShare >= 0.25 && f.bodyChars >= 100);
  // The owner's heuristic: more than 3 families in body text, or a decorative or script face in paragraphs.
  const flags = [];
  if (bodyFamilies.length > 3) flags.push("more-than-3-body-families");
  if (decorativeBody.length) flags.push(`decorative-body: ${decorativeBody.map((f) => f.family).join(", ")}`);
  // Informational, not a fault on its own: many faces across the whole page, headings included.
  const busy = meaningful.length > 3;
  return {
    families: list.map(({ family, kind, share, bodyShare, decorative, system }) => ({ family, kind, share, bodyShare, decorative, system })),
    familiesAll: list.length,
    familiesMeaningful: meaningful.length,
    bodyFamilies: bodyFamilies.length,
    webfontsDeclared: [...new Set(fonts.webfonts.map((w) => normFamily(w.family)))].length,
    textChars: total,
    flags,
    inappropriate: flags.length > 0,
    busy,
  };
}

