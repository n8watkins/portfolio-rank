const host = (u, base) => {
  try {
    return new URL(u, base).hostname.toLowerCase().replace(/^www\./, "");
  } catch {
    return null;
  }
};
const fold = (s) =>
  String(s ?? "")
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase();
const tokens = (s) => fold(s).split(/[^a-z0-9]+/).filter((t) => t.length >= 3);

// ---------- (1) meta tags ----------
const GENERIC_TITLE = /^(react app|vite \+ react.*|vite app|create next app|next\.?js app|document|untitled|home|index|welcome|my portfolio|portfolio|my app|astro|gatsby.*|svelte ?kit app|vue app|angular app|nuxt app)$/i;
const GENERIC_DESC = /(web site created using create-react-app|generated by create next app|created with vite|lorem ipsum|^my portfolio\.?$|^portfolio\.?$|^a? ?(personal )?portfolio (website|site)\.?$|^description$|your description here)/i;
const PLACEHOLDER_HOST = /^(example\.(com|org|net)|localhost|127\.0\.0\.1|yourdomain\.com|your-?(site|website|domain|portfolio)\.\w+|mysite\.com|domain\.com|website\.com)$/i;

function metaCheck(head, siteHost, fetchRow, base) {
  if (!head || head.error) return null;
  const title = head.title || null;
  const desc = head.description || null;
  const canon = head.canonical?.[0] ?? null;
  const canonHost = canon ? host(canon, base) : null;
  const ogImg = head.og.image || null;
  const ogImgAbs = ogImg ? (() => { try { return new URL(ogImg, base).href; } catch { return null; } })() : null;
  // fetch.mjs checked the first og:image (or twitter:image) it found with a regex; use it when it is the same address.
  let ogImageLoads = null;
  if (ogImgAbs && fetchRow?.ogImage?.url === ogImgAbs) ogImageLoads = fetchRow.ogImage.loads;
  const ogUrlHost = head.og.url ? host(head.og.url, base) : null;
  return {
    title,
    titleOk: !!title && !GENERIC_TITLE.test(title.trim()),
    titleGeneric: !!title && GENERIC_TITLE.test(title.trim()),
    description: desc,
    descriptionOk: !!desc && desc.length >= 20 && !GENERIC_DESC.test(desc.trim()),
    descriptionGeneric: !!desc && (desc.length < 20 || GENERIC_DESC.test(desc.trim())),
    canonical: canon,
    canonicalOk: !!canonHost && siteHost.has(canonHost),
    canonicalWrongHost: !!canonHost && !siteHost.has(canonHost),
    ogTitle: !!head.og.title,
    ogDescription: !!head.og.description,
    ogImage: ogImg,
    ogImageRelative: !!ogImg && !/^https?:\/\//i.test(ogImg),
    ogImageLoads,
    ogImagePlaceholder: !!ogImgAbs && PLACEHOLDER_HOST.test(host(ogImgAbs) ?? ""),
    ogUrlWrongHost: !!ogUrlHost && !siteHost.has(ogUrlHost),
    twitterCard: head.twitter.card || null,
    twitterCardOk: /^(summary|summary_large_image|app|player)$/i.test(head.twitter.card ?? ""),
  };
}

// ---------- (2) structured data ----------
const PLACEHOLDER_NAME = /^(john|jane) doe$|^your name$|^lorem ipsum|^(first ?name )?last ?name$|^name surname$|^author( name)?$|^full name$|^my name$|^username$|^test user$/i;
const SOCIAL = /(^|\.)(github\.com|linkedin\.com|twitter\.com|x\.com|instagram\.com|facebook\.com|youtube\.com|medium\.com|dev\.to|behance\.net|dribbble\.com|stackoverflow\.com|gitlab\.com|bsky\.app|threads\.net|mastodon\.\w+|t\.me|wa\.me|leetcode\.com|kaggle\.com|codepen\.io|hashnode\.\w+|substack\.com|orcid\.org|scholar\.google\.com)$/i;
