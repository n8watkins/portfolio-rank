// Pages that stand where a listed site was and answer 200: a sale or parking
// lander, a web server's default page, a host's error or placeholder page, a
// maintenance or removal notice, a gambling site the domain now forwards to,
// and the browser's own error page. Each is a failed check on the health
// check's existing weekly-counted rule (pipeline/health.mjs nextHealth), never
// a removal, and only on positive evidence. The fixtures in
// tests/fixtures/reading/ are the pages saved by the 2026-11-23 benchmark
// (emails and phone numbers replaced). Deterministic; no network.
import { test } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { PARKING_DOMAINS, PARKING_PHRASES, httpGate, parkedPage, placeholderPage } from "../pipeline/gate.mjs";
import { checkSite, gamblingWords, nextHealth, redirectVerdict } from "../pipeline/health.mjs";

const fixture = (name) => fs.readFileSync(path.join(import.meta.dirname, "fixtures", "reading", name), "utf8");
const page = (url, body) => async () => ({ status: 200, ok: true, url, text: async () => body });

test("http://gianlucafiore.it: nginx's default page is not the site, by its title and by its sentence", async () => {
  const html = fixture("gianlucafiore.it.plain.html");
  assert.equal(parkedPage({ finalUrl: "http://gianlucafiore.it/", html }), "not the site: nginx's default page");
  assert.equal(placeholderPage({ html: html.replace(/<title>[^<]*<\/title>/, "") }), "nginx's default page", "the sentence alone");
  const gate = await httpGate("http://gianlucafiore.it", { fetchImpl: page("http://gianlucafiore.it/", html) });
  assert.deepEqual([gate.status, gate.reason], ["parked", "not the site: nginx's default page"]);
  const r = await checkSite({ url: "http://gianlucafiore.it", name: "Gianluca Fiore" }, { fetchImpl: page("http://gianlucafiore.it/", html) });
  assert.deepEqual([r.ok, r.reason], [false, "not the site: nginx's default page"]);
  // The existing ladder: a first failure is suspect (still shown), not down, not removed.
  assert.equal(nextHealth(null, r).health, "suspect");
});

test("host and server pages that stand in for the site, each from its saved page", () => {
  assert.equal(parkedPage({ finalUrl: "https://iamharshdoshi.com/", html: fixture("iamharshdoshi.com.plain.html") }), "not the site: a maintenance page");
  // A removal notice and nothing else (synthetic, the shape of aditya113141.github.io's page).
  assert.equal(parkedPage({ finalUrl: "https://ana.github.io/", html: fixture("removed-notice.synthetic.html") }), "not the site: a notice that the site was removed");
  // Streamlit: the plain request loops on redirects, so the browser's reading decides.
  assert.equal(parkedPage({ finalUrl: "https://datasciencefolio.streamlit.app/", text: fixture("datasciencefolio.streamlit.app.rendered.txt"), title: "Streamlit" }), "not the site: Streamlit's error page");
  const muse = "https://muse.ai/s/neel-patel-portfolio-tomas-style-xzxx6m5xtl3huxh/44rs8uC9gN1nl-HjxoLSA9T-gfn27ZKRX8RhxAimXuw";
  assert.equal(parkedPage({ finalUrl: muse, text: fixture("muse.ai.rendered.txt"), title: "Muse — Your Personal AI Agent" }), "not the site: a not-found page");
  assert.equal(parkedPage({ finalUrl: muse, html: fixture("muse.ai.plain.html") }), "not the site: a not-found page", "its plain answer too");
  for (const [title, body, what] of [
    ["Apache2 Ubuntu Default Page: It works", "<h1>Apache2 Ubuntu Default Page</h1><p>It works!</p>", "Apache's default page"],
    ["", "<h1>It works!</h1>", "Apache's default page"],
    ["IIS Windows Server", '<img src="iisstart.png" alt="IIS">', "IIS's default page"],
    ["Domain Default page", "<p>This page is generated by Plesk, the leading hosting automation software.</p>", "Plesk's default page"],
    ["Site not found", "<h1>There isn't a GitHub Pages site here.</h1>", "GitHub Pages' page for no site"],
    ["Index of /", '<h1>Index of /</h1><table><tr><th><a href="?C=N;O=D">Name</a></th></tr></table>', "an empty directory listing"],
  ])
    assert.equal(placeholderPage({ html: `<html><head><title>${title}</title></head><body>${body}</body></html>` }), what, title || body);
});

test("sale and parking landers on hosts and in words found by the benchmark", async () => {
  assert.equal(parkedPage({ finalUrl: "https://expireddomains.com/domain/swaroop.codes?utm_source=redi", text: fixture("swaroop.codes.rendered.txt") }), "redirects to expireddomains.com");
  const gate = await httpGate("https://swaroop.codes", { fetchImpl: page("https://expireddomains.com/domain/swaroop.codes?utm_source=redi", "<title>swaroop.codes — Buy this expired domain | ED.com</title>") });
  assert.deepEqual([gate.status, gate.reason], ["parked", "redirects to expireddomains.com"]);
  const inb = fixture("saurabhdaware.in.inb-link.html");
  assert.equal(parkedPage({ finalUrl: "https://inb.link/saurabhdaware.in", html: inb }), "redirects to inb.link");
  assert.equal(parkedPage({ finalUrl: "https://www.saurabhdaware.in/", html: inb }), 'parking phrase: "default domain lander"', "its words on the site's own address");
  assert.equal(parkedPage({ finalUrl: "http://findonlineresults.com/?dn=abdulmomin.dev" }), "redirects to findonlineresults.com");
  assert.equal(parkedPage({ finalUrl: "https://karrarnazim.space/", title: "karrarnazim.space - Buy this expired domain", text: "" }), 'parking phrase: "buy this expired domain"');
});

test("the Python parking tables match gate.mjs", () => {
  const py = spawnSync("python3", ["-I", "-B", "-c",
    "import sys, json; sys.path.insert(0, sys.argv[1]); import check_parking_redirects as c; print(json.dumps([sorted(c.PARKING_DOMAINS), c.PARKING_PHRASES]))",
    fileURLToPath(new URL("../pipeline/", import.meta.url))], { encoding: "utf8" });
  assert.equal(py.status, 0, py.stderr);
  assert.deepEqual(JSON.parse(py.stdout), [[...PARKING_DOMAINS].sort(), PARKING_PHRASES]);
});

test("a real page that mentions a server, a host or an error in a sentence is the site", () => {
  const real = fixture("collinskoechportfolio.web.app.plain.html");
  assert.equal(parkedPage({ finalUrl: "https://collinskoechportfolio.web.app/", html: real }), null, "a real portfolio's saved page");
  const portfolio = (title, body) => `<html><head><title>${title}</title></head><body><h1>Jane Doe</h1>${body}<a href="https://github.com/janedoe">GitHub</a></body></html>`;
  const short = [
    portfolio("Jane Doe | DevOps", "<p>I set up nginx for a living: if you see the nginx welcome page on a client's site, call me.</p>"),
    portfolio("Jane Doe", "<p>My app runs on Streamlit and Apache. It works!</p>"),
    portfolio("Jane Doe | Projects", "<p>Project: a maintenance tracker for factories.</p>"),
    portfolio("Page not found? Jane Doe designs 404 pages", "<p>A gallery of not-found pages I designed.</p>"),
    portfolio("Jane Doe", "<p>Everything I built is listed below. Removed projects are archived.</p>"),
  ];
  for (const html of short) assert.equal(parkedPage({ finalUrl: "https://jane.dev/", html }), null, html);
  // A long post that quotes the default page word for word is a page with something to say.
  const post = portfolio("How I configured nginx", `<p>The page said: "If you see this page, the nginx web server is successfully installed and working."</p><p>${"Then I wrote a server block, reloaded and checked the logs. ".repeat(30)}</p>`);
  assert.equal(parkedPage({ finalUrl: "https://jane.dev/", html: post }), null);
  // A directory listing with files in it is not empty.
  assert.equal(placeholderPage({ html: `<title>Index of /</title><h1>Index of /</h1><a href="../">Parent Directory</a><a href="cv.pdf">cv.pdf</a>` }), undefined);
});

test("a listed domain that now forwards to a gambling site fails the check; a move to the person's new site does not", () => {
  for (const [url, to, file] of [
    ["https://www.abhisheksah.dev", "https://angkasa338win.com/", "abhisheksah.dev.rendered.txt"],
    ["https://indrajeet.me", "https://app.lunabet89.com/", "indrajeet.me.rendered.txt"],
    ["https://vallarasuk.com", "https://pika77terkuat.com/game/pgr/3", "vallarasuk.com.rendered.txt"],
  ]) {
    const v = redirectVerdict(url, to, "Some One", fixture(file));
    assert.equal(v?.fail, `redirects to ${new URL(to).hostname.split(".").slice(-2).join(".")}, a gambling site`, url);
  }
  // Moves to the person's own site whose projects mention games: one word, or none of the list.
  const mine = "Jane Doe. Projects: a poker hand evaluator in Rust; a scheduling app. GitHub, contact.";
  assert.deepEqual(redirectVerdict("https://jane.github.io", "https://janedoe.dev/", "Jane Doe", mine), { moved: true, hijack: false, to: "janedoe.dev" });
  // Without a move, gambling words never count (a page about a lottery simulator and slot machines).
  assert.equal(redirectVerdict("https://jane.dev", "https://jane.dev/", "Jane Doe", "A lottery simulator and a slot machine game, built in Unity."), null);
  assert.deepEqual(gamblingWords("SLOT gacor, Nổ Hũ and casinos"), ["slot", "gacor", "no hu", "casino"]);
});

test("a site the browser shows only its own error page for does not load", async () => {
  const r = await checkSite(
    { url: "https://broken.example", name: "Ann Lee" },
    {
      fetchImpl: page("https://broken.example/", "<div id=root></div>"),
      render: async () => ({ status: 200, finalUrl: "chrome-error://chromewebdata/", title: "", text: "", html: "" }),
    }
  );
  assert.deepEqual([r.ok, r.reason], [false, "does not load (the browser's error page)"]);
});
