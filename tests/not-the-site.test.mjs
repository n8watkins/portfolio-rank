test("a server's default page from a stale address passes when the https or www form shows the site", async () => {
  const nginx = fixture("gianlucafiore.it.plain.html");
  const site = `<html><head><title>Gianluca Fiore</title></head><body><h1>Gianluca Fiore</h1><p>About Me. Projects. Contact. I write about technology.</p></body></html>`;
  const seen = [];
  const fetchImpl = async (u) => {
    seen.push(u);
    if (u.startsWith("http://gianlucafiore.it")) return { status: 200, ok: true, url: "http://gianlucafiore.it/", text: async () => nginx };
    if (u.startsWith("https://gianlucafiore.it")) throw Object.assign(new TypeError("fetch failed"), { cause: { code: "ERR_TLS_CERT_ALTNAME_INVALID", message: "Hostname/IP does not match certificate's altnames" } });
    return { status: 200, ok: true, url: "https://www.gianlucafiore.it/", text: async () => site };
  };
  const gate = await httpGate("http://gianlucafiore.it", { fetchImpl });
  assert.deepEqual([gate.status, gate.finalUrl], ["live", "https://www.gianlucafiore.it/"]);
  assert.deepEqual(seen, ["http://gianlucafiore.it", "https://gianlucafiore.it/", "https://www.gianlucafiore.it/"]);
  const r = await checkSite({ url: "http://gianlucafiore.it", name: "Gianluca Fiore" }, { fetchImpl });
  assert.equal(r.ok, true);
  // Other verdicts are not retried: a parked page is parked at once.
  const parkedSeen = [];
  const sedo = await httpGate("https://abdulmomin.dev", { fetchImpl: async (u) => (parkedSeen.push(u), { status: 200, ok: true, url: "https://abdulmomin.dev/", text: async () => "<title>abdulmomin.dev - abdulmomin Resources and Information.</title>" }) });
  assert.deepEqual([sedo.status, parkedSeen.length], ["parked", 1]);
});
