// Pages that stand where a listed site was and answer 200: a sale or parking
// lander, a web server's default page, a host's error or placeholder page, a
// maintenance or removal notice, a gambling site the domain now forwards to,
// and the browser's own error page. Each is a failed check on the health
// check's ladder (pipeline/health.mjs nextHealth, or the temporary pool when
// it runs), never a removal, and only on positive evidence. The fixtures in
// tests/fixtures/reading/ are the pages saved by the 2026-11-23 benchmark
// (emails and phone numbers replaced; the removal notice is synthetic).
// Deterministic; no network.
import { test } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { PARKING_DOMAINS, PARKING_PHRASES, httpGate, parkedPage, placeholderPage } from "../pipeline/gate.mjs";
import { BROWSER_ERROR_PAGE, checkSite, gamblingWords, nextHealth, redirectVerdict } from "../pipeline/health.mjs";

const fixture = (name) => fs.readFileSync(path.join(import.meta.dirname, "fixtures", "reading", name), "utf8");
const page = (url, body) => async () => ({ status: 200, ok: true, url, text: async () => body });

test("http://gianlucafiore.it: nginx's default page is not the site, by its own sentence, when no other form of the address shows the site", async () => {
  const html = fixture("gianlucafiore.it.plain.html");
  assert.equal(parkedPage({ finalUrl: "http://gianlucafiore.it/", html }), "not the site: nginx's default page");
  assert.equal(placeholderPage({ html: html.replace(/<title>[^<]*<\/title>/, "") }), "nginx's default page", "the sentence alone");
  const gate = await httpGate("http://gianlucafiore.it", { fetchImpl: page("http://gianlucafiore.it/", html) });
  assert.deepEqual([gate.status, gate.reason], ["parked", "not the site: nginx's default page"]);
  const r = await checkSite({ url: "http://gianlucafiore.it", name: "Gianluca Fiore" }, { fetchImpl: page("http://gianlucafiore.it/", html) });
  assert.deepEqual([r.ok, r.reason], [false, "not the site: nginx's default page"]);
  // The existing ladder: a first failure is suspect (still shown), not down, not removed.
  assert.equal(nextHealth(null, r).health, "suspect");
});

